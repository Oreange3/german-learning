/**
 * Original practice texts for this class.
 * Lesen and Lücken both draw from this file so a daily text is not the same
 * one every few days. Nothing here is copied from an exam publisher.
 */

function reading(id, level, title, text, en, qs) {
  return {
    id,
    level,
    title,
    text,
    en,
    questions: qs.map((q, index) => ({
      id: `${id}-${index + 1}`,
      prompt: q[0],
      en: q[1],
      choices: q[2],
      answer: q[3],
    })),
  }
}

function cloze(id, level, title, parts, extra) {
  return { id, level, title, parts, extra }
}

