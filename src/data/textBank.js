export function readingsFor(level) {
  return readings.filter((item) => item.level === level)
}

export function clozesFor(level) {
  return clozes.filter((item) => item.level === level)
}

export function clozeBlanks(item) {
  return item.parts.filter((part) => Array.isArray(part)).map(([answer, id]) => ({ id, answer }))
}

export function clozePool(item) {
  return [...clozeBlanks(item).map((blank) => blank.answer), ...item.extra]
}
