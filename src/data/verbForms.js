/** One infinitive, five gaps. The form changes with the sentence. */

function card(spec) {
  const particle = spec.particle || ''
  const prefixNote = particle ? ', and the prefix stays at the end' : ''
  const aux = spec.aux || 'haben'
  const perfectDe = aux === 'sein' ? 'Ich bin ___.' : 'Ich habe ___.'

  return {
    id: spec.id || spec.de,
    de: spec.de,
    en: spec.en,
    presentNote: spec.presentNote || '',
    scenes: [
      {
        id: 'ich',
        label: 'Present',
        slot: 'ich, present',
        needs: spec.ichNeeds || `-e${prefixNote}`,
        extra: spec.ichExtra || '',
        build: spec.ichBuild || '',
        why: particle
          ? 'Present, ich. The prefix stays at the end of the sentence.'
          : 'Present. The verb agrees with ich.',
        en: spec.ichEn || `I ${spec.i} at ten.`,
        de: spec.ichDe || (particle ? `Ich ___ um zehn ${particle}.` : 'Ich ___ um zehn.'),
        answer: spec.ich,
      },
      {
        id: 'future',
        label: 'Future',
        slot: 'after werden',
        needs: 'the infinitive',
        extra: '',
        build: '',
        why: 'Future. werden is already in the sentence, so this verb stays in the infinitive.',
        en: spec.futEn || `I will ${spec.i} later.`,
        de: spec.futDe || 'Ich werde später ___.',
        answer: spec.de,
      },
      {
        id: 'want',
        label: 'Want',
        slot: 'after wollen',
        needs: 'the infinitive, with no zu',
        extra: '',
        build: '',
        why: 'wollen takes the bare infinitive. Do not add zu.',
        en: spec.wantEn || `I want to ${spec.i}.`,
        de: spec.wantDe || 'Ich will ___.',
        answer: spec.de,
      },
      {
        id: 'er',
        label: 'Present',
        slot: 'er, present',
        needs: spec.erNeeds || `-t${prefixNote}`,
        extra: spec.erExtra || '',
        build: spec.erBuild || '',
        why: particle
          ? 'Present, er. The prefix stays at the end of the sentence.'
          : 'Present. The verb agrees with er.',
        en: spec.erEn || `He ${spec.he} at noon.`,
        de: spec.erDe || (particle ? `Er ___ um zwölf ${particle}.` : 'Er ___ um zwölf.'),
        answer: spec.er,
      },
      {
        id: 'perfect',
        label: 'Perfect',
        slot: 'the perfect',
        needs: spec.perfNeeds || (aux === 'sein' ? 'the participle, with sein' : 'ge- + -t'),
        extra: spec.perfExtra || '',
        build: spec.perfBuild || '',
        why: aux === 'sein' ? 'Perfect. This verb uses sein plus the participle.' : 'Perfect. haben plus the participle.',
        en: spec.perfEn || `I have ${spec.done}.`,
        de: spec.perfDe || perfectDe,
        answer: spec.part,
      },
    ],
  }
}

